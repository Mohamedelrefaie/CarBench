#!/usr/bin/env python3
"""Generate per-model unified-training configs for the rebuttal baseline.

For each of the 9 trainable benchmark models, take its base config (architecture)
and overlay the shared unified training block (`unified_training.yaml`). Only the
training knobs are unified; every architecture parameter is preserved verbatim.

Writes:  experiments/unified_config/configs/<name>.yaml
Prints:  per-model summary of which keys were overridden, and asserts that no
         non-training (architecture) key changed value.

Usage:
    python experiments/unified_config/generate_unified_configs.py
"""
from __future__ import annotations

import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(os.path.dirname(HERE))
OUT_DIR = os.path.join(HERE, "configs")

MODELS = [
    "transolver", "transolver_large", "transolver_plus",
    "regdgcnn", "point_transformer", "pointnet", "pointnet_large",
    "pointmae", "fno",
]

# Training keys the unified recipe is allowed to change. Everything else in a base
# config is treated as architecture/model-specific and must stay byte-identical.
TRAINING_KEYS = set()  # filled from unified_training.yaml at runtime


def load_yaml(path):
    with open(path) as f:
        return yaml.safe_load(f) or {}


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    unified = load_yaml(os.path.join(HERE, "unified_training.yaml"))
    # If the batch probe has run, use its result for batch_size (overrides placeholder).
    probe_path = os.path.join(HERE, "batch_probe_results.json")
    if os.path.exists(probe_path):
        import json
        unified["batch_size"] = json.load(open(probe_path))["unified_batch"]
        print(f"Using probed unified batch_size = {unified['batch_size']}\n")
    global TRAINING_KEYS
    TRAINING_KEYS = set(unified.keys())

    print(f"Unified training block ({len(TRAINING_KEYS)} keys): "
          f"{sorted(TRAINING_KEYS)}\n")

    for name in MODELS:
        base_path = os.path.join(REPO_ROOT, "models", name, "config.yaml")
        base = load_yaml(base_path)

        merged = dict(base)
        changed = {}
        for k, v in unified.items():
            old = base.get(k, "<absent>")
            if old != v:
                changed[k] = (old, v)
            merged[k] = v

        # Safety: assert no architecture key was silently altered.
        for k in base:
            if k not in TRAINING_KEYS and merged[k] != base[k]:
                raise AssertionError(f"{name}: architecture key '{k}' changed!")

        out_path = os.path.join(OUT_DIR, f"{name}.yaml")
        header = (
            f"# AUTO-GENERATED by generate_unified_configs.py — do not edit by hand.\n"
            f"# Base: models/{name}/config.yaml (architecture preserved)\n"
            f"# Training overlay: experiments/unified_config/unified_training.yaml\n"
        )
        with open(out_path, "w") as f:
            f.write(header)
            yaml.safe_dump(merged, f, sort_keys=True, default_flow_style=False)

        overrides = ", ".join(f"{k}:{o}->{n}" for k, (o, n) in sorted(changed.items()))
        print(f"[{name:<18}] wrote {os.path.relpath(out_path, REPO_ROOT)}")
        print(f"    overrode: {overrides or '(already matched)'}")

    print(f"\nDone. {len(MODELS)} configs written to {os.path.relpath(OUT_DIR, REPO_ROOT)}/")


if __name__ == "__main__":
    main()
